function zone(id: TakeoutZone['zone'], name: string, pick: TakeoutZone['pick'], gs: G[], day: number): TakeoutZone {
  return {
    zone: id,
    name,
    pick,
    groups: gs
      .filter((g) => g.days[day] && g.days[day]!.length > 0)
      .map((g) => ({ label: g.label, items: g.days[day]!, ...(g.eastOnly ? { eastOnly: true } : {}) })),
  }
}

